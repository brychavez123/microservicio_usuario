-- Limpieza (en orden inverso a las dependencias)
BEGIN
    FOR t IN (SELECT table_name FROM user_tables
              WHERE table_name IN ('MODERACION_ACCION', 'COMENTARIO', 'TEMA', 'CATEGORIA', 'USUARIO', 'ROL')) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

CREATE TABLE ROL (
    ID     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(30) NOT NULL,
    CONSTRAINT UQ_ROL_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE USUARIO (
    ID             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NOMBRE         VARCHAR2(100) NOT NULL,
    EMAIL          VARCHAR2(150) NOT NULL,
    PASSWORD       VARCHAR2(100) NOT NULL,   -- hash BCrypt
    ROL_ID         NUMBER        NOT NULL,
    FECHA_REGISTRO DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT UQ_USUARIO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT FK_USUARIO_ROL FOREIGN KEY (ROL_ID) REFERENCES ROL (ID)
);

CREATE INDEX IX_USUARIO_ROL ON USUARIO (ROL_ID);

